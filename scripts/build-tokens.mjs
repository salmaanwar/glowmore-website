// GM Design System -> CSS. Reads design/tokens.json (variables) and design/styles.json (text + effect styles)
// and writes src/styles/tokens.css plus src/styles/varmap.json (Figma variable name -> CSS custom property).
import fs from 'node:fs';

const tokens = JSON.parse(fs.readFileSync('design/tokens.json', 'utf8'));
const styles = JSON.parse(fs.readFileSync('design/styles.json', 'utf8'));
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// Desktop site: Light colours, Desktop spacing / type, English fonts.
const MODE = ['Light', 'Desktop', 'EN', 'Value'];
const pick = v => { for (const m of MODE) if (v.resolved && v.resolved[m] !== undefined) return v.resolved[m]; for (const m of MODE) if (v.values && v.values[m] !== undefined) return v.values[m]; return Object.values(v.values || {})[0]; };
const varmap = {};
const varval = {}; /* resolved Light value per colour variable, to detect paints shown in another mode */
const lines = [];
for (const v of Object.values(tokens.variables)) {
  const css = (v.code_syntax && v.code_syntax.WEB || '').match(/var\((--[^)]+)\)/);
  const name = css ? css[1] : '--' + slug(v.name);
  let val = pick(v);
  if (val && typeof val === 'object' && val.alias) { const t = tokens.variables[val.alias]; val = t ? pick(t) : undefined; }
  if (val === undefined || val === null) continue;
  if (v.type === 'number') val = /font-weight/.test(v.name) ? String(val) : val + 'px';
  if (v.type === 'string') val = /font-weight/.test(v.name) ? String(val) : `"${val}"`;
  lines.push(`  ${name}: ${val};`);
  varmap[v.name] = name;
  if (v.type === 'color') varval[v.name] = String(val).toUpperCase();
}

// Fonts: the DS uses Gilroy (body, 4 weights) and Safira March (display, 4 weights).
const FONT = { 'Gilroy-Light': ['Gilroy', 300], 'Gilroy-Regular': ['Gilroy', 400], 'Gilroy-Medium': ['Gilroy', 500], 'Gilroy-Bold': ['Gilroy', 700] };
const SAFIRA = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700 };
const face = (family, file, weight, fmt) => `@font-face { font-family: "${family}"; src: url("/fonts/${file}") format("${fmt}"); font-weight: ${weight}; font-style: normal; font-display: swap; }`;
const faces = [
  ...Object.entries(FONT).map(([f, [fam, w]]) => face(fam, f + '.ttf', w, 'truetype')),
  ...Object.entries(SAFIRA).map(([s, w]) => face('Safira March', `SafiraMarch-${s}.otf`, w, 'opentype')),
];
const fontOf = (family, style) => FONT[family] ? { fam: '"Gilroy", system-ui, sans-serif', w: FONT[family][1] } : { fam: '"Safira March", Georgia, serif', w: SAFIRA[style.replace(/\s/g, '')] || 400 };

// Text styles -> .ts-<slug>
const textCss = [];
const textmap = {};
for (const t of styles.text) {
  const f = fontOf(t.family, t.style);
  const b = t.b || {};
  const v = (k, raw) => b[k] && varmap[b[k]] ? `var(${varmap[b[k]]})` : raw;
  const lh = t.lh.unit === 'PIXELS' ? t.lh.value + 'px' : t.lh.unit === 'PERCENT' ? t.lh.value / 100 : 'normal';
  const ls = t.ls.unit === 'PIXELS' ? t.ls.value + 'px' : (t.ls.value / 100) + 'em';
  const cls = 'ts-' + slug(t.name);
  textmap[t.name] = cls;
  textCss.push(`.${cls} { font-family: ${f.fam}; font-weight: ${f.w}; font-size: ${v('fontSize', t.size + 'px')}; line-height: ${v('lineHeight', lh)}; letter-spacing: ${v('letterSpacing', ls)};${t.dec === 'UNDERLINE' ? ' text-decoration: underline;' : t.dec === 'STRIKETHROUGH' ? ' text-decoration: line-through;' : ''}${t.tc === 'UPPER' ? ' text-transform: uppercase;' : ''} }`);
}

// Effect styles -> --fx-<slug>
const fx = [];
const fxmap = {};
for (const e of styles.effects) {
  const parts = e.effects.filter(x => x.type === 'DROP_SHADOW' || x.type === 'INNER_SHADOW').map(x => {
    const col = x.colorVar && varmap[x.colorVar] ? `var(${varmap[x.colorVar]})` : `rgba(${x.color.slice(0, 3).map(c => Math.round(c * 255)).join(',')},${x.color[3]})`;
    return `${x.type === 'INNER_SHADOW' ? 'inset ' : ''}${x.x || 0}px ${x.y || 0}px ${x.blur || 0}px ${x.spread || 0}px ${col}`;
  });
  if (!parts.length) continue;
  const name = '--fx-' + slug(e.name);
  fx.push(`  ${name}: ${parts.join(', ')};`);
  fxmap[e.name] = name;
}

fs.mkdirSync('src/styles', { recursive: true });
fs.writeFileSync('src/styles/tokens.css', `/* Generated by scripts/build-tokens.mjs from design/tokens.json + design/styles.json. Do not edit. */\n${faces.join('\n')}\n:root {\n${lines.join('\n')}\n${fx.join('\n')}\n}\n${textCss.join('\n')}\n`);
fs.writeFileSync('src/styles/varmap.json', JSON.stringify({ vars: varmap, vals: varval, text: textmap, fx: fxmap }));
console.log(`tokens.css: ${lines.length} variables, ${textCss.length} text styles, ${fx.length} effects`);

// Image fills: hash -> file name in public/img (extension differs per image).
const imgs = {};
for (const f of fs.readdirSync('public/img')) imgs[f.replace(/\.[^.]+$/, '')] = f;
fs.writeFileSync('src/styles/imgindex.json', JSON.stringify(imgs));
